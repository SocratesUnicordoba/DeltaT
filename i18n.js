// Devuelve una copia del módulo con los textos traducidos. Conserva ids, run()
// y los métodos auxiliares, así que el resto del código no nota la diferencia.
function trMod(m) {
  if (LANG === 'es') return m;
  const t = TRM[m.id] || {};
  const lbl = c => (t.labels && t.labels[c.id || ('sep:' + c.label)]) || c.label;
  return Object.assign(Object.create(Object.getPrototypeOf(m)), m, {
    group: I18N_GRUPO[m.group] || m.group,
    short: t.short || m.short, title: t.title || m.title, desc: t.desc || m.desc, eq: t.eq || m.eq,
    controls: (m.controls || []).map(c => Object.assign({}, c, {
      label: lbl(c),
      options: c.options && t.options && t.options[c.id]
        ? c.options.map((o, i) => [o[0], t.options[c.id][i] || o[1]]) : c.options,
    })),
    views: (m.views || []).map(v => Object.assign({}, v, {
      title: (t.views && t.views[v.id]) || v.title,
      hint: (t.hints && t.hints[v.id]) || v.hint,
    })),
    buttons: m.buttons && m.buttons.map((b, i) => Object.assign({}, b, { label: (t.buttons && t.buttons[i]) || b.label })),
  });
}
